import { test, expect } from '@playwright/test'
test('聊天发送、停止、预算拒绝与中文输入法事件', async ({ page }) => {
  await page.goto('/#/chat')
  const input = page.getByRole('textbox', {name:'输入消息'})
  await input.fill('输入法尚未确认')
  await input.dispatchEvent('keydown',{key:'Enter',code:'Enter',isComposing:true})
  await expect(page.locator('.turn')).toHaveCount(0)
  await input.fill('如何控制 Token 成本？')
  await page.getByRole('button',{name:'发送消息',exact:true}).click()
  await page.getByRole('button',{name:'停止生成',exact:true}).click()
  await expect(page.locator('.message-notice')).toContainText('未完成')
  await expect(page.locator('.user-bubble')).toHaveText('如何控制 Token 成本？')
  await page.selectOption('#scenario','budget')
  await input.fill('保留这条草稿')
  await page.getByRole('button',{name:'发送消息',exact:true}).click()
  await expect(input).toHaveValue('保留这条草稿')
  await expect(page.locator('.turn')).toHaveCount(1)
})
test('重试中断保留旧答案，第三次完成后禁用重试', async ({page}) => {
  await page.goto('/#/chat')
  await page.getByRole('textbox',{name:'输入消息'}).fill('如何控制成本？')
  await page.getByRole('button',{name:'发送消息',exact:true}).click()
  await expect(page.locator('.message-actions')).toBeVisible()
  const old = await page.locator('.message-text').innerText()
  await page.selectOption('#scenario','disconnect')
  await page.getByRole('button',{name:/重新生成/}).click()
  await expect(page.locator('.message-notice')).toContainText('上一版有效答案')
  await expect(page.locator('.message-text')).toHaveText(old)
  await page.selectOption('#scenario','normal')
  await page.getByRole('button',{name:/重新生成/}).click()
  await expect(page.locator('.attempt-count')).toHaveText('3/3')
  await expect(page.getByRole('button',{name:/重新生成/})).toBeDisabled()
})
