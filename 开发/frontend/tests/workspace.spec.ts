test('FE-A04：助手标签可读、可键盘切换，草稿需显式启用', async ({page}) => {
  await page.goto('/#/assistant')
  const basic=page.getByRole('button',{name:'基础配置',exact:true})
  const versions=page.getByRole('button',{name:/版本记录/})
  await expect(basic).toHaveAttribute('aria-pressed','true')
  const contrast=await basic.evaluate(el=>{
    function luminance(text:string){const rgb=text.match(/[\d.]+/g)!.slice(0,3).map(Number).map(v=>v/255).map(v=>v<=.04045?v/12.92:((v+.055)/1.055)**2.4);return rgb[0]*.2126+rgb[1]*.7152+rgb[2]*.0722}
    const s=getComputedStyle(el),l=[luminance(s.color),luminance(s.backgroundColor)].sort((a,b)=>b-a);return (l[0]+.05)/(l[1]+.05)
  })
  expect(contrast).toBeGreaterThanOrEqual(4.5)
  await versions.focus(); await page.keyboard.press('Enter')
  await expect(versions).toHaveAttribute('aria-pressed','true')
  await basic.click()
  await page.getByRole('textbox',{name:'系统提示词',exact:false}).fill('先确认问题，再提供已核实的步骤。')
  await page.getByRole('button',{name:'保存为示例草稿',exact:true}).click()
  const row=page.getByRole('row').filter({hasText:'v1.3'})
  await expect(row).toContainText('草稿')
  await row.getByRole('button',{name:'启用示例',exact:true}).click()
  await expect(row).toContainText('当前启用')
})
