import { test, expect } from '@playwright/test'

test('概览统计来自会话与账本，聊天后同步更新', async ({ page }) => {
  await page.goto('/')
  await expect(page).toHaveURL(/#\/overview$/)
  const stats = page.locator('.overview-stats')
  await expect(stats.locator('.stat-value').nth(0)).toContainText('3')
  await expect(stats.locator('.stat-value').nth(1)).toContainText('2')
  await expect(stats.locator('.stat-value').nth(2)).toHaveText('¥7.82')
  await page.getByRole('button', { name: '开始一段对话' }).click()
  await page.getByRole('textbox', { name: '输入消息' }).fill('怎样整理产品说明？')
  await page.getByRole('button', { name: '发送消息', exact: true }).click()
  await expect(page.locator('.message-actions')).toBeVisible()
  await page.getByRole('link', { name: '工作空间概览', exact: true }).click()
  await expect(stats.locator('.stat-value').nth(0)).toContainText('4')
  await expect(stats.locator('.stat-value').nth(1)).toContainText('3')
  await expect(stats.locator('.stat-value').nth(2)).not.toHaveText('¥7.82')
  await expect(page.locator('.overview-conversations')).toContainText('怎样整理产品说明？')
})

